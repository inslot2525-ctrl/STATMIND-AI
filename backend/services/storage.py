"""
File storage: uploads, model artifacts, predictions and reports.

Interchangeable backends, chosen with STORAGE_BACKEND:
  * local  : files under STATMIND_DATA_DIR (default; single machine or shared volume)
  * s3     : any S3-compatible bucket - AWS S3, Cloudflare R2, MinIO
  * lakefs : a lakeFS repository, through its S3 gateway (set by LAKEFS_ENDPOINT)

Objects are addressed by *keys* such as "uploads/<sha>.csv" or "models/<id>.pkl".
Keys are always generated by the server; user input is never turned into a key
without validation. pandas and joblib need real files, so the S3 backend keeps a
local read-through cache (safe because uploads and models are immutable).
"""
import hashlib
import os
import re
import shutil
import tempfile

import config

DATA_DIR = config.DATA_DIR
UPLOAD_DIR = os.path.join(DATA_DIR, "uploads")
MODEL_DIR = os.path.join(DATA_DIR, "models")
PREDICTION_DIR = os.path.join(DATA_DIR, "predictions")
REPORT_DIR = os.path.join(DATA_DIR, "reports")
CACHE_DIR = os.path.join(DATA_DIR, "cache")
TMP_DIR = os.path.join(DATA_DIR, "tmp")

KINDS = {"uploads", "models", "predictions", "reports"}

for _dir in (UPLOAD_DIR, MODEL_DIR, PREDICTION_DIR, REPORT_DIR, CACHE_DIR, TMP_DIR):
    os.makedirs(_dir, exist_ok=True)

ALLOWED_DATA_EXTENSIONS = (".csv", ".xlsx", ".xls")
MAX_UPLOAD_BYTES = int(config.MAX_UPLOAD_MB * 1024 * 1024)

CONTENT_TYPES = {
    ".csv": "text/csv",
    ".xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    ".xls": "application/vnd.ms-excel",
    ".html": "text/html",
    ".pkl": "application/octet-stream",
}

_SAFE_NAME = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._()-]*$")


# ----------------------------------------------------------------- validation
def resolve_in(directory: str, name: str) -> str:
    """
    Return the absolute path of `name` inside `directory`.

    Raises ValueError if the name contains path separators or unusual characters,
    or would resolve to a location outside `directory`.
    """
    if not name or not _SAFE_NAME.match(name) or ".." in name:
        raise ValueError("Invalid file name.")

    base = os.path.realpath(directory)
    path = os.path.realpath(os.path.join(base, name))

    if os.path.commonpath([base, path]) != base:
        raise ValueError("Invalid file name.")

    return path


def make_key(kind: str, name: str) -> str:
    """Build a storage key from a kind and a validated file name."""
    if kind not in KINDS:
        raise ValueError(f"Unknown storage kind: {kind}")
    resolve_in(DATA_DIR, name)  # validates the name
    return f"{kind}/{name}"


def split_key(key: str) -> tuple[str, str]:
    kind, _, name = (key or "").partition("/")
    make_key(kind, name)  # validates
    return kind, name


def safe_component(value: str) -> str:
    """Turn arbitrary text (e.g. a column name) into a safe file-name fragment."""
    cleaned = re.sub(r"[^A-Za-z0-9_-]+", "_", str(value)).strip("_")
    return cleaned[:60] or "x"


def data_extension(filename: str) -> str:
    """Return the lower-case extension of an uploaded data file, or raise ValueError."""
    ext = os.path.splitext(filename or "")[1].lower()
    if ext not in ALLOWED_DATA_EXTENSIONS:
        raise ValueError("Only CSV and Excel files are supported.")
    return ext


def content_type_for(name: str) -> str:
    return CONTENT_TYPES.get(os.path.splitext(name)[1].lower(), "application/octet-stream")


# ------------------------------------------------------------------- backends
class LocalStorage:
    name = "local"

    def _path(self, key: str) -> str:
        kind, name = split_key(key)
        return resolve_in(os.path.join(DATA_DIR, kind), name)

    def put_file(self, key: str, source_path: str, move: bool = False) -> str:
        dest = self._path(key)
        if move:
            os.replace(source_path, dest)
        else:
            shutil.copyfile(source_path, dest)
        return dest

    def put_bytes(self, key: str, data: bytes) -> None:
        with open(self._path(key), "wb") as f:
            f.write(data)

    def exists(self, key: str) -> bool:
        return os.path.exists(self._path(key))

    def local_path(self, key: str) -> str:
        path = self._path(key)
        if not os.path.exists(path):
            raise ValueError("Stored file not found.")
        return path

    def presigned_url(self, key: str, download_name: str) -> str | None:
        return None  # served through the API's signed download endpoint instead


class S3Storage:
    name = "s3"

    def __init__(self):
        import boto3

        if not config.S3_BUCKET:
            raise RuntimeError("S3_BUCKET must be set when STORAGE_BACKEND=s3.")
        self.bucket = config.S3_BUCKET
        self.prefix = config.S3_PREFIX.strip("/") + "/" if config.S3_PREFIX else ""
        self.client = boto3.client(
            "s3",
            endpoint_url=config.S3_ENDPOINT_URL,
            region_name=config.S3_REGION,
        )

    def _object(self, key: str) -> str:
        split_key(key)  # validates
        return self.prefix + key

    def _cache_path(self, key: str) -> str:
        kind, name = split_key(key)
        directory = os.path.join(CACHE_DIR, kind)
        os.makedirs(directory, exist_ok=True)
        return resolve_in(directory, name)

    def put_file(self, key: str, source_path: str, move: bool = False) -> str:
        self.client.upload_file(
            source_path, self.bucket, self._object(key),
            ExtraArgs={"ContentType": content_type_for(key)},
        )
        cached = self._cache_path(key)
        if move:
            os.replace(source_path, cached)
        else:
            shutil.copyfile(source_path, cached)
        return cached

    def put_bytes(self, key: str, data: bytes) -> None:
        self.client.put_object(
            Bucket=self.bucket, Key=self._object(key), Body=data, ContentType=content_type_for(key)
        )

    def exists(self, key: str) -> bool:
        from botocore.exceptions import ClientError

        try:
            self.client.head_object(Bucket=self.bucket, Key=self._object(key))
            return True
        except ClientError:
            return False

    def local_path(self, key: str) -> str:
        from botocore.exceptions import ClientError

        cached = self._cache_path(key)
        if not os.path.exists(cached):
            fd, tmp = tempfile.mkstemp(dir=TMP_DIR)
            os.close(fd)
            try:
                self.client.download_file(self.bucket, self._object(key), tmp)
                os.replace(tmp, cached)
            except ClientError:
                raise ValueError("Stored file not found.")
            finally:
                if os.path.exists(tmp):
                    os.remove(tmp)
        return cached

    def presigned_url(self, key: str, download_name: str) -> str | None:
        return self.client.generate_presigned_url(
            "get_object",
            Params={
                "Bucket": self.bucket,
                "Key": self._object(key),
                "ResponseContentDisposition": f'attachment; filename="{download_name}"',
            },
            ExpiresIn=config.DOWNLOAD_LINK_SECONDS,
        )


class LakeFSStorage(S3Storage):
    """
    lakeFS speaks the S3 protocol: the bucket is the repository and the first
    path segment is the branch, so files land on the branch as uncommitted
    changes until lakefs_versioning.commit() is called.
    """

    name = "lakefs"

    def __init__(self):
        import boto3

        self.bucket = config.LAKEFS_REPOSITORY
        self.prefix = config.LAKEFS_BRANCH + "/"
        self.client = boto3.client(
            "s3",
            endpoint_url=config.LAKEFS_ENDPOINT,
            aws_access_key_id=config.LAKEFS_ACCESS_KEY_ID,
            aws_secret_access_key=config.LAKEFS_SECRET_ACCESS_KEY,
            region_name="us-east-1",
        )

    def presigned_url(self, key: str, download_name: str) -> str | None:
        # The lakeFS gateway does not accept presigned URLs; downloads go through the API
        return None


_storage = None


def get_storage():
    """Return the configured storage backend (created once)."""
    global _storage
    if _storage is None:
        if config.STORAGE_BACKEND == "lakefs":
            _storage = LakeFSStorage()
        elif config.STORAGE_BACKEND == "s3":
            _storage = S3Storage()
        elif config.STORAGE_BACKEND == "local":
            _storage = LocalStorage()
        else:
            raise RuntimeError(f"Unknown STORAGE_BACKEND: {config.STORAGE_BACKEND}")
    return _storage


# -------------------------------------------------------------------- uploads
def save_upload(upload_file) -> tuple[str, str, str]:
    """
    Stream an UploadFile into storage under a content-addressed name.

    Returns (stored_name, key, local_path). The original client filename is
    never used as a path; callers keep it only as metadata.
    """
    if not upload_file.filename:
        raise ValueError("No file uploaded.")

    ext = data_extension(upload_file.filename)
    sha256 = hashlib.sha256()
    size = 0

    fd, tmp_path = tempfile.mkstemp(dir=TMP_DIR, suffix=".part")
    try:
        with os.fdopen(fd, "wb") as out:
            while chunk := upload_file.file.read(1024 * 1024):
                size += len(chunk)
                if size > MAX_UPLOAD_BYTES:
                    raise ValueError(
                        f"File is too large. Maximum size is {MAX_UPLOAD_BYTES // (1024 * 1024)} MB."
                    )
                sha256.update(chunk)
                out.write(chunk)

        if size == 0:
            raise ValueError("Uploaded file is empty.")

        stored_name = f"{sha256.hexdigest()[:32]}{ext}"
        key = make_key("uploads", stored_name)
        local_path = get_storage().put_file(key, tmp_path, move=True)
        return stored_name, key, local_path
    finally:
        if os.path.exists(tmp_path):
            os.remove(tmp_path)
